export function getFashionItemById(id?: string): FashionDecorItem | undefined {
  if (!id) return undefined;
  if (id === 'rug_01_co_xanh_hoa') return FASHION_DECOR_CATALOG.find((item) => item.id === 'rug_peach');
  if (id === 'bowl_pink_paw') return FASHION_DECOR_CATALOG.find((item) => item.id === 'bowl_meo_no_hong');
  if (id === 'bowl_royal_gold') return FASHION_DECOR_CATALOG.find((item) => item.id === 'bowl_hoang_gia_den_vang');
  if (id === 'bowl_cyber_dispenser') return FASHION_DECOR_CATALOG.find((item) => item.id === 'bowl_vuong_mien_xanh_ngoc');
  if (id === 'ball_jingle_bell') return FASHION_DECOR_CATALOG.find((item) => item.id === 'ball_luc_lac');
  if (id === 'ball_rainbow') return FASHION_DECOR_CATALOG.find((item) => item.id === 'ball_lo_xo');
  if (id === 'toy_plush_mouse') return FASHION_DECOR_CATALOG.find((item) => item.id === 'ball_chuot');
  if (id === 'toy_feather_wand') return FASHION_DECOR_CATALOG.find((item) => item.id === 'ball_gay_meo');
  return FASHION_DECOR_CATALOG.find((item) => item.id === id);
}

